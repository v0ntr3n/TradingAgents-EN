# tradingagents/core/engine/data_contract.py
"""
Data contract definition

Provides a declarative contract for data interaction between Agents, including:
- DataLayer: Data hierarchical enumeration
- DataAccess: Data Access Statement
- AgentDataContract: Agent data contract
"""

from enum import Enum
from typing import List, Set, Optional
from dataclasses import dataclass, field


class DataLayer(str, Enum):
    """
    Data hierarchical enumeration
    
    Define a five-layer data structure, each layer has different responsibilities and access rights:
    - CONTEXT: Basic contextual information (stock code, date, etc.)
    - RAW_DATA: Raw data (prices, news, financial data, etc.)
    - ANALYSIS_DATA: Analysis results (structured technical indicators, valuation indicators, etc.)
    - REPORTS: Analysis reports (text reports generated by each analyst)
    - DECISIONS: Decision data (debate history, trading signals, risk assessments, etc.)
    """
    CONTEXT = "context"
    RAW_DATA = "raw_data"
    ANALYSIS_DATA = "analysis_data"
    REPORTS = "reports"
    DECISIONS = "decisions"


@dataclass
class DataAccess:
    """
    Data Access Statement
    
    Declare the Agent s access requirements to a certain data layer.
    
    Attributes:
        layer: data layer
        fields: A list of fields that need to be accessed. An empty list indicates access to all data in the entire layer.
        required: Whether it is required, False means optional (no error will be reported when the data does not exist)
    
    Examples:
        # access specific fields
        DataAccess(layer=DataLayer.CONTEXT, fields=["ticker", "trade_date"])
        
        # Access all data in the entire layer
        DataAccess(layer=DataLayer.REPORTS)  # fields Default is empty list
        
        # Optional access
        DataAccess(layer=DataLayer.DECISIONS, fields=["debate"], required=False)
    """
    layer: DataLayer
    fields: List[str] = field(default_factory=list)
    required: bool = True
    
    def __post_init__(self):
        """Validate field type"""
        if not isinstance(self.layer, DataLayer):
            raise ValueError(f"layer must be DataLayer, got {type(self.layer)}")
        if not isinstance(self.fields, list):
            raise ValueError(f"fields must be list, got {type(self.fields)}")


@dataclass
class AgentDataContract:
    """
    Agent data contract
    
    Define Agent s data input and output specifications to implement declarative data dependency.
    
    Attributes:
        agent_id: Agent unique identifier
        inputs: Enter data declaration list
        outputs: Output data declaration list
        depends_on: Dependent Agent ID collection
        description: Contract description
    
    Examples:
        MARKET_ANALYST_CONTRACT = AgentDataContract(
            agent_id="market_analyst",
            inputs=[
                DataAccess(layer=DataLayer.CONTEXT, fields=["ticker", "company_name"]),
                DataAccess(layer=DataLayer.RAW_DATA, fields=["price_data"]),
            ],
            outputs=[
                DataAccess(layer=DataLayer.ANALYSIS_DATA, fields=["technical"]),
                DataAccess(layer=DataLayer.REPORTS, fields=["market_report"]),
            ],
            depends_on={"data_collector"},
            description="Market Analyst - responsible for technical analysis"
        )
    """
    agent_id: str
    inputs: List[DataAccess] = field(default_factory=list)
    outputs: List[DataAccess] = field(default_factory=list)
    depends_on: Set[str] = field(default_factory=set)
    description: str = ""
    
    def __post_init__(self):
        """Verify contract integrity"""
        if not self.agent_id:
            raise ValueError("agent_id cannot be empty")
        
        # Make sure depends_on is a collection
        if isinstance(self.depends_on, (list, tuple)):
            self.depends_on = set(self.depends_on)
    
    def get_input_layers(self) -> Set[DataLayer]:
        """Get all input data layers"""
        return {access.layer for access in self.inputs}
    
    def get_output_layers(self) -> Set[DataLayer]:
        """Get all output data layers"""
        return {access.layer for access in self.outputs}
    
    def get_input_fields(self, layer: DataLayer) -> List[str]:
        """Get the input field list of the specified layer"""
        for access in self.inputs:
            if access.layer == layer:
                return access.fields
        return []
    
    def get_output_fields(self, layer: DataLayer) -> List[str]:
        """Get the output field list of the specified layer"""
        for access in self.outputs:
            if access.layer == layer:
                return access.fields
        return []
    
    def has_input_access(self, layer: DataLayer, field: str = None) -> bool:
        """Check if there is input access for the specified layer/field"""
        for access in self.inputs:
            if access.layer == layer:
                if not field:
                    return True
                if not access.fields or field in access.fields:
                    return True
        return False
    
    def has_output_access(self, layer: DataLayer, field: str = None) -> bool:
        """Check if there is output access for the specified layer/field"""
        for access in self.outputs:
            if access.layer == layer:
                if not field:
                    return True
                if not access.fields or field in access.fields:
                    return True
        return False

