# Asynchronous policy processor: Returns ReplyCandidate if hit, None if not hit; main is not allowed to return None
PathHandler = Callable[["AssistantRequest"], Awaitable[Optional[ReplyCandidate]]]


@dataclass
class AssistantRequest:
    """Context bag for a single conversation (common to both JSON/SSE modes).

    on_progress: Only streaming mode injection, used to execute tool execution progress events (tool_started, etc.)
    Pushed to the SSE adapter; None for non-streaming.
    tools_used: The tool names accumulated in the main path and the adapter exception branch must also be available.
    """

    service: Any
    user_message: str
    conversation_id: Optional[str] = None
    assistant_settings: Optional[dict] = None
    is_im: bool = False
    history_messages: Optional[List[Any]] = None
    user_profile: Optional[dict] = None
    current_topic_title: Optional[str] = None
    memory_block: str = ""
    on_progress: Optional[Callable[[Dict[str, Any]], Awaitable[None]]] = None
    tools_used: List[str] = field(default_factory=list)


@dataclass
class RegisteredPath:
    route_id: str
    priority: int
    handler: PathHandler
    route_type: str = ROUTE_TYPE_ANSWER
    description: str = ""


class PathRegistry:
    """Explicit priority path registry. Assemble once, resolve once."""

    def __init__(self) -> None:
        self._paths: List[RegisteredPath] = []

    def register(
        self,
        route_id: str,
        priority: int,
        handler: PathHandler,
        route_type: str = ROUTE_TYPE_ANSWER,
        description: str = "",
    ) -> "PathRegistry":
        if any(p.route_id == route_id for p in self._paths):
            raise ValueError(f"path {route_id!r} Duplicate registration")
        self._paths.append(
            RegisteredPath(
                route_id=route_id,
                priority=priority,
                handler=handler,
                route_type=route_type,
                description=description,
            )
        )
        return self

    def ordered(self) -> List[RegisteredPath]:
        return sorted(self._paths, key=lambda p: (p.priority, p.route_id))

    async def resolve(self, request: AssistantRequest) -> ReplyCandidate:
        """Try in order of priority; the main path must be fully understood, otherwise an error will be thrown (a program defect)."""
        for path in self.ordered():
            candidate = await path.handler(request)
            if candidate is not None:
                candidate.meta.setdefault("route_priority", path.priority)
                return candidate
        raise RuntimeError("PathRegistry No path hits (the main path must be fully understood)")
