def _merge_input_config(
    existing: Dict[str, Any],
    defaults: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Merge and completion input_config: Existing fields are retained, and missing fields are supplemented from default values.

    - existing: input_config already in the database (may only have some fields)
    - defaults: Complete default input_config (generated by workflow_type)
    - Return: merged input_config, existing fields remain unchanged, and missing ones are filled in.
    """
    if not existing or not existing.get("fields"):
        return defaults

    existing_field_names = {f["name"] for f in existing.get("fields", [])}
    merged_fields = list(existing.get("fields", []))

    for default_field in defaults.get("fields", []):
        if default_field["name"] not in existing_field_names:
            merged_fields.append(default_field)

    # Reorder by order
    merged_fields.sort(key=lambda f: f.get("order", 999))
    return {"fields": merged_fields}


