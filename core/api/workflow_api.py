    def execute(
        self,
        workflow_id: str,
        inputs: Dict[str, Any],
        legacy_config: Optional[Dict[str, Any]] = None,
        progress_callback: Optional[Callable] = None,
        task_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Execute workflow

        Args:
            workflow_id: Workflow ID
            inputs: input parameters
            legacy_config: Legacy agent configuration (LLM, models, etc.)
            progress_callback: Progress callback function
            task_id: Task ID (task_id of the task center, used to perform trajectory association. If not passed, it will be randomly generated)

        Returns:
            Execution result
        """
        # Try loading workflow from database or file
        data = self.get(workflow_id)

        # If not found, try loading from system preset workflow
        if data is None:
            provider = get_default_workflow_provider()
            workflow = provider.get_system_workflow(workflow_id)
            if workflow:
                data = workflow.to_dict()
                self._log_workflow_source(workflow_id, "system_preset", data)

        if data is None:
            return {"success": False, "error": "Workflow does not exist"}

        try:
            definition = WorkflowDefinition.from_dict(data)
            logger.info(f"📋 [WorkflowAPI] Execute workflow definition: {definition.id} - {definition.name}")

            # Prepare input parameters
            prepared_inputs = self._prepare_inputs(inputs)

            logger.info(f"[Workflow execution] input parameters: ticker={prepared_inputs.get('ticker')}, trade_date={prepared_inputs.get('trade_date')}")

            # Create a configured engine (preferably using the incoming task_id to perform trajectory association)
            task_id = task_id or str(uuid.uuid4())
            engine = WorkflowEngine(legacy_config=legacy_config, task_id=task_id)
            engine.load(definition)
            result = engine.execute(prepared_inputs, progress_callback=progress_callback)

            return {
                "success": True,
                "result": result,
                "execution": engine.last_execution.model_dump() if engine.last_execution else None,
            }
        except Exception as e:
            import traceback
            traceback.print_exc()
            return {"success": False, "error": str(e)}

    def _prepare_system_variables(
        self,
        stock_code: str,
        analysis_date: str
    ) -> Dict[str, Any]:
        """
        Prepare system variables (obtained uniformly at the beginning of the workflow)

        Get it from the database first, fast and not affected by API current limit

        Args:
            stock_code: Stock code
            analysis_date: Parse a date (string or datetime object)

        Returns:
            System variable dictionary
        """
        system_vars = {}

        try:
            from tradingagents.utils.stock_utils import StockUtils
            from app.core.database import get_mongo_db_sync  # Use sync version

            # Make sure analysis_date is a plain date string (YYYY-MM-DD)
            if isinstance(analysis_date, datetime):
                analysis_date = analysis_date.strftime('%Y-%m-%d')
            elif isinstance(analysis_date, str):
                # Handle strings that may contain time, such as "2026-01-14T00:00:00" or "2026-01-14 00:00:00"
                if 'T' in analysis_date:
                    analysis_date = analysis_date.split('T')[0]
                elif ' ' in analysis_date:
                    analysis_date = analysis_date.split()[0]

            market_info = StockUtils.get_market_info(stock_code)
            is_china = market_info.get('is_china', False)
            effective_data_date = analysis_date
            stable_data_note = ""

            if is_china:
                try:
                    from core.tools.trade_date_policy import apply_stable_data_cutoff, build_stable_data_cutoff_note

                    effective_data_date = apply_stable_data_cutoff(analysis_date)
                    stable_data_note = build_stable_data_cutoff_note(
                        analysis_date,
                        effective_data_date,
                        subject="A Stock daily frequency stable data",
                    )
                except Exception as e:
                    logger.warning(f"⚠️ Calculation of stable data date failed, falling back to analysis date: {e}")

            system_vars["effective_data_date"] = effective_data_date
            system_vars["stable_data_note"] = stable_data_note

            # 1. Obtain basic stock information (company name, industry) from the database
            company_name = stock_code
            industry = "unknown"

            if is_china:
                try:
                    db = get_mongo_db_sync()  # Use sync version

                    # Get it first from stock_basic_info
                    stock_info = db.stock_basic_info.find_one(
                        {"$or": [{"code": stock_code}, {"symbol": stock_code}]},
                        {"_id": 0, "name": 1, "industry": 1}
                    )

                    if stock_info:
                        company_name = stock_info.get("name", stock_code)
                        industry = stock_info.get("industry", "unknown")
                        logger.info(f"📊 [System variables - database] Company name: {company_name}, Industry: {industry}")
                    else:
                        logger.warning(f"⚠️ Stock not found in database {stock_code} basic information")
                except Exception as e:
                    logger.warning(f"⚠️ Failed to obtain basic stock information from database: {e}")

            system_vars["company_name"] = company_name
            system_vars["industry"] = industry

            # 2. Get current price from database
            current_price = "unknown"
            current_price_context_date = ""

            if is_china:
                try:
                    db = get_mongo_db_sync()  # Use sync version
                    logger.info(f"🔍 [Price inquiry] Start checking stocks {stock_code} price...")

                    # Prioritize getting prices no later than the stable date from market_quotes to avoid pulling the summary back to the analysis day.
                    logger.info(f"🔍 [Price inquiry] steps 1: Query stable date prices from market_quotes...")
                    quote = None
                    date_candidates = [effective_data_date]
                    compact_effective_date = effective_data_date.replace('-', '')
                    if compact_effective_date != effective_data_date:
                        date_candidates.append(compact_effective_date)

                    for date_candidate in date_candidates:
                        quote = db.market_quotes.find_one(
                            {
                                "$or": [{"code": stock_code}, {"symbol": stock_code}],
                                "trade_date": {"$lte": date_candidate},
                            },
                            {"_id": 0, "close": 1, "trade_date": 1},
                            sort=[("trade_date", -1)]
                        )
                        if quote:
                            break

                    logger.info(f"🔍 [Price inquiry] market_quotes Query results: {quote}")

                    if quote and quote.get("close"):
                        current_price = str(quote["close"])
                        current_price_context_date = str(quote.get("trade_date") or "")
                        logger.info(f"✅ [System variables - database] current price: ¥{current_price} (Date: {quote.get('trade_date', 'N/A')})")
                    else:
                        logger.warning(
                            f"⚠️ Stock not found in database {stock_code} on stable date {effective_data_date} and previous price information"
                        )
                except Exception as e:
                    logger.warning(f"⚠️ Failed to get current price from database: {e}")
                    import traceback
                    traceback.print_exc()

            system_vars["current_price"] = current_price
            system_vars["current_price_context_date"] = current_price_context_date

            # 3. market information
            market_name = "A shares" if is_china else "Hong Kong stocks" if market_info.get('is_hk') else "US stocks"
            system_vars["market_name"] = market_name

            # 4. currency information
            if is_china:
                system_vars["currency_name"] = "RMB"
                system_vars["currency_symbol"] = "¥"
            elif market_info.get('is_hk'):
                system_vars["currency_name"] = "Hong Kong dollar"
                system_vars["currency_symbol"] = "HK$"
            else:
                system_vars["currency_name"] = "US dollars"
                system_vars["currency_symbol"] = "$"

            # 5. date information
            from datetime import timedelta
            system_vars["current_date"] = analysis_date
            start_date = (datetime.strptime(analysis_date, '%Y-%m-%d') - timedelta(days=365)).strftime('%Y-%m-%d')
            system_vars["start_date"] = start_date

            # 6. 🆕 Industry/stock analysis dimension injection
            try:
                from app.services.analysis_profile_service import AnalysisProfileService

                # Query industry analysis dimensions
                if industry and industry != "unknown":
                    industry_dims = AnalysisProfileService.get_industry_dimensions_sync(industry)
                    system_vars.update(industry_dims)

                # Query individual stock analysis dimensions (covering industry dimensions)
                stock_dims = AnalysisProfileService.get_stock_dimensions_sync(stock_code)
                system_vars.update(stock_dims)
            except Exception as e:
                logger.warning(f"⚠️ Failed to obtain analysis dimensions (does not affect the main process): {e}")

            logger.info(f"✅ [system variables] Ready to complete: {list(system_vars.keys())}")
            logger.info(f"   - company_name: {company_name}")
            logger.info(f"   - industry: {industry}")
            logger.info(f"   - current_price: {current_price}")
            logger.info(f"   - effective_data_date: {effective_data_date}")
            logger.info(f"   - market_name: {market_name}")
            if system_vars.get("industry_dimensions"):
                logger.info(f"   - 🏭 Infused with industry analysis dimensions")
            if system_vars.get("stock_dimensions"):
                logger.info(f"   - 📊 Injected into individual stock analysis dimension")

        except Exception as e:
            logger.error(f"❌ Failed to prepare system variables: {e}")
            import traceback
            traceback.print_exc()

        return system_vars

    def _prepare_inputs(self, inputs: Dict[str, Any]) -> Dict[str, Any]:
        """
        Prepare workflow input parameters

        Handle field mapping, state initialization, etc.
        """
        prepared = dict(inputs)

        # Parse debate round number from input
        depth_mapping = {
            "fast": {"debate": 1, "risk": 1},
            "Basics": {"debate": 1, "risk": 1},
            "Standard": {"debate": 1, "risk": 2},
            "Depth": {"debate": 2, "risk": 2},
            "Comprehensive": {"debate": 3, "risk": 3},
        }
        research_depth = prepared.get("research_depth", "Standard")
        depth_config = depth_mapping.get(research_depth, depth_mapping["标准"])

        # Inject debate configuration into input
        prepared["_max_debate_rounds"] = depth_config["debate"]
        prepared["_max_risk_rounds"] = depth_config["risk"]

        # A9-P1: Risk self-debate switch (single node replaces risk triangle multi-round debate, only depth/full file)
        # Priority: environment variable RISK_SELF_DEBATE (on/off, one-click rollback)> Enter explicit override > Gear default
        _self_debate_mode = str(os.environ.get("RISK_SELF_DEBATE", "auto")).strip().lower()
        if _self_debate_mode in ("on", "1", "true"):
            prepared["_risk_self_debate"] = True
        elif _self_debate_mode in ("off", "0", "false"):
            prepared["_risk_self_debate"] = False
        elif "risk_self_debate" in prepared:
            # Allow callers to explicitly override per task (truthy determination)
            prepared["_risk_self_debate"] = bool(prepared.get("risk_self_debate"))
        else:
            # Default: only the depth/full scale is enabled, the other gears follow the original risk triangle path
            prepared["_risk_self_debate"] = research_depth in ("Depth", "Comprehensive")
        logger.info(
            f"[A9-P1] Risk self debate switch: {prepared['_risk_self_debate']} "
            f"(mode={_self_debate_mode}, depth={research_depth})"
        )

        # A3: Investment debate parallel start switch (first round of optimistic/cautious researcher briefings in parallel, instead of serial relay)
        # Priority: Environment variable RESEARCH_PARALLEL_OPENING (on/off, one-click rollback)> Enter explicit override > Enabled by default
        _parallel_opening_mode = str(
            os.environ.get("RESEARCH_PARALLEL_OPENING", "auto")
        ).strip().lower()
        if _parallel_opening_mode in ("on", "1", "true"):
            prepared["_parallel_opening"] = True
        elif _parallel_opening_mode in ("off", "0", "false"):
            prepared["_parallel_opening"] = False
        elif "parallel_opening" in prepared:
            # Allow callers to explicitly override per task (truthy determination)
            prepared["_parallel_opening"] = bool(prepared.get("parallel_opening"))
        else:
            # Enabled in all gears by default: Parallel start just changes the first round of serial relay to parallel.
            # The semantics of the debate remain unchanged (each independently produces an initial briefing based on the same analyst material)
            prepared["_parallel_opening"] = True
        logger.info(
            f"[A3] Investment debate parallel opening switch: {prepared['_parallel_opening']} "
            f"(mode={_parallel_opening_mode})"
        )

        # Map field names to be compatible with original agents
        if "ticker" in prepared:
            prepared["company_of_interest"] = prepared["ticker"]
        if "analysis_date" in prepared and prepared["analysis_date"]:
            date_str = prepared["analysis_date"]
            if isinstance(date_str, str):
                # Handle strings that may contain times
                if "T" in date_str:
                    date_str = date_str.split("T")[0]
                elif " " in date_str:
                    date_str = date_str.split()[0]
                prepared["trade_date"] = date_str
            else:
                prepared["trade_date"] = str(date_str)[:10]
        else:
            prepared["trade_date"] = datetime.now().strftime("%Y-%m-%d")

        # Initialize the state fields required by the original agent
        prepared.setdefault("investment_debate_state", {
            "history": "", "bull_history": "", "bear_history": "",
            "current_response": "", "count": 0
        })
        prepared.setdefault("risk_debate_state", {
            "history": "", "risky_history": "", "safe_history": "",
            "neutral_history": "", "current_risky_response": "",
            "current_safe_response": "", "current_neutral_response": "",
            "latest_speaker": "", "count": 0
        })

        # Analysis report fields
        for field in ["market_report", "sentiment_report", "news_report", "fundamentals_report"]:
            prepared.setdefault(field, "")

        # Tool call counter
        for field in ["market_tool_call_count", "sentiment_tool_call_count",
                      "news_tool_call_count", "fundamentals_tool_call_count"]:
            prepared.setdefault(field, 0)

        # Analyst Independent News History
        for field in ["_market_messages", "_social_messages",
                      "_news_messages", "_fundamentals_messages"]:
            prepared.setdefault(field, [])

        # Research result fields
        for field in ["bull_report", "bear_report", "investment_plan", "trader_investment_plan"]:
            prepared.setdefault(field, "")

        logger.info(f"[Workflow execution] Analysis depth: {research_depth}, Debate rounds: {depth_config['debate']}, Risk rounds: {depth_config['risk']}")

        # 🆕 Prepare system variables (company name, industry, current price, etc.)
        ticker = prepared.get("ticker")
        analysis_date = prepared.get("analysis_date") or prepared.get("trade_date")

        if ticker and analysis_date:
            system_vars = self._prepare_system_variables(ticker, analysis_date)
            prepared.update(system_vars)

        return prepared
    
    def validate(self, data: Dict[str, Any]) -> Dict[str, Any]:
        """Validate workflow definition"""
        try:
            # If there is no id during verification, a temporary one will be generated.
            if "id" not in data or not data["id"]:
                data["id"] = f"temp_{uuid.uuid4()}"
            # 🔥 Convert datetime object to string (Pydantic validation requires string type)
            if "created_at" in data and isinstance(data["created_at"], datetime):
                data["created_at"] = data["created_at"].isoformat()
            if "updated_at" in data and isinstance(data["updated_at"], datetime):
                data["updated_at"] = data["updated_at"].isoformat()
            definition = WorkflowDefinition.from_dict(data)
            result = self._validator.validate(definition)

            return {
                "is_valid": result.is_valid,
                "errors": [str(e) for e in result.errors],
                "warnings": [str(w) for w in result.warnings],
            }
        except Exception as e:
            return {"is_valid": False, "errors": [str(e)], "warnings": []}

