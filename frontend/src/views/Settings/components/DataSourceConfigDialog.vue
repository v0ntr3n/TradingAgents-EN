// Handle submission
const handleSubmit = async () => {
  if (!formRef.value) return

  try {
    await formRef.value.validate()
    loading.value = true

    // 🔥 Fix: Send truncated API Key directly to the backend
    // The backend will determine whether the truncated value matches the original value in the database
    const payload: any = buildPayload()

    // Add a log to show the sent API Key
    if (payload.api_key) {
      console.log('🔍 [save] send API Key:', payload.api_key, '(length:', payload.api_key.length, ')')
    } else {
      console.log('🔍 [save] API Key is empty')
    }

    if (payload.api_secret) {
      console.log('🔍 [save] send API Secret:', payload.api_secret, '(length:', payload.api_secret.length, ')')
    } else {
      console.log('🔍 [save] API Secret is empty')
    }

    // Handle placeholders (your_xxx or your-xxx)
    if ('api_key' in payload) {
      const apiKey = payload.api_key || ''
      // If it is a placeholder, delete the field (do not update)
      if (apiKey.startsWith('your_') || apiKey.startsWith('your-')) {
        console.log('🔍 [save] API Key is a placeholder, delete the field')
        delete payload.api_key
      }
    }

    if ('api_secret' in payload) {
      const apiSecret = payload.api_secret || ''
      // If it is a placeholder, delete the field (do not update)
      if (apiSecret.startsWith('your_') || apiSecret.startsWith('your-')) {
        console.log('🔍 [save] API Secret is a placeholder, delete the field')
        delete payload.api_secret
      }
    }

    if (isEdit.value) {
      // Update data source
      await configApi.updateDataSourceConfig(formData.value.name, payload)
      ElMessage.success('Data source updated successfully')
    } else {
      // Create data source
      await configApi.addDataSourceConfig(payload)
      ElMessage.success('Data source created successfully')
    }

    emit('success')
    handleClose()
  } catch (error: any) {
    console.error('Failed to save data source:', error)

    // Extract detailed error information
    let errorMessage = 'Failed to save data source'

    // Try to extract messages from different error structures
    if (error?.response?.data?.detail) {
      // FastAPI HTTPException wrong format
      errorMessage = error.response.data.detail
    } else if (error?.response?.data?.message) {
      // Custom error format
      errorMessage = error.response.data.message
    } else if (error?.message) {
      // Standard Error object
      errorMessage = error.message
    }

    ElMessage.error(errorMessage)
  } finally {
    loading.value = false
  }
}

