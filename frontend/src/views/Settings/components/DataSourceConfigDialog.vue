      },
      trigger: 'blur'
    }
  ],
  qmt_init_markets: [
    {
      validator: (_rule: any, value: string, callback: any) => {
        if (!isQmtType.value) {
          callback()
          return
        }
        if (!value || !value.trim()) {
          callback(new Error('Please enter initialization market'))
          return
        }
        callback()
      },
      trigger: 'blur'
    }
  ],
  // API Key Validation rules
  api_key: [
    {
      validator: (_rule: any, value: string, callback: any) => {
        // If empty, allow (indicates using environment variables)
        if (!value || value.trim() === '') {
          callback()
          return
        }

        const trimmedValue = value.trim()

        // If it is a truncated key (containing "...") , Allow (meaning not modified)
        if (trimmedValue.includes('...')) {
          callback()
          return
        }

        // If it is a placeholder, allow (meaning not modified)
        if (trimmedValue.startsWith('your_') || trimmedValue.startsWith('your-')) {
          callback()
          return
        }

        // If it is a newly entered key, the length must be > 10
        if (trimmedValue.length <= 10) {
          callback(new Error('API Key Length must be greater than 10 characters'))
          return
        }

        callback()
      },
      trigger: 'blur'
    }
  ]
}

