      width="680px"
      top="5vh"
      :close-on-click-modal="false"
      class="legal-dialog"
    >
      <div class="legal-content" v-html="agreementHtml"></div>
      <template #footer>
        <el-button @click="agreementDialogVisible = false">close</el-button>
      </template>
    </el-dialog>

    <!-- Privacy Policy Pop-up -->
    <el-dialog
      v-model="privacyDialogVisible"
      title="privacy policy"
      width="680px"
      top="5vh"
      :close-on-click-modal="false"
      class="legal-dialog"
    >
      <div class="legal-content" v-html="privacyHtml"></div>
      <template #footer>
        <el-button @click="privacyDialogVisible = false">close</el-button>
      </template>
    </el-dialog>
  </div>
</template>

<script setup lang="ts">
import { reactive, ref, onMounted } from 'vue'
import { useRouter } from 'vue-router'
import { ElMessage } from 'element-plus'
import { useAuthStore } from '@/stores/auth'
import { renderMarkdown } from '@/utils/markdown'

const router = useRouter()
const authStore = useAuthStore()

const loginFormRef = ref()
const loginLoading = ref(false)

// Agreement related status
const agreedToTerms = ref(false)
const agreementDialogVisible = ref(false)
const privacyDialogVisible = ref(false)
const agreementHtml = ref('')
const privacyHtml = ref('')

const loginForm = reactive({
  username: '',
  password: '',
  rememberMe: false
})

// Initialization: Check whether the agreement has been agreed
onMounted(() => {
  const accepted = localStorage.getItem('terms-accepted')
  if (accepted === 'true') {
    agreedToTerms.value = true
  }
})

// Load and display the user agreement
const showAgreementDialog = async () => {
  if (!agreementHtml.value) {
    try {
      const response = await fetch('/legal/USER_AGREEMENT.md')
      if (response.ok) {
        const mdText = await response.text()
        agreementHtml.value = renderMarkdown(mdText)
      } else {
        agreementHtml.value = '<p>The user agreement failed to load, please try again later.</p>'
      }
    } catch {
      agreementHtml.value = '<p>The user agreement failed to load, please try again later.</p>'
    }
  }
  agreementDialogVisible.value = true
}

// Load and display privacy policy
const showPrivacyDialog = async () => {
  if (!privacyHtml.value) {
    try {
      const response = await fetch('/legal/PRIVACY_POLICY.md')
      if (response.ok) {
        const mdText = await response.text()
        privacyHtml.value = renderMarkdown(mdText)
      } else {
        privacyHtml.value = '<p>Privacy policy failed to load, please try again later.</p>'
      }
    } catch {
      privacyHtml.value = '<p>Privacy policy failed to load, please try again later.</p>'
    }
  }
  privacyDialogVisible.value = true
}

const loginRules = {
  username: [
    { required: true, message: 'Please enter username', trigger: 'blur' }
  ],
  password: [
    { required: true, message: 'Please enter password', trigger: 'blur' },
    { min: 6, message: 'The password length cannot be less than 6 characters', trigger: 'blur' }
  ]
}

const handleLogin = async () => {
  // Prevent duplicate submissions
  if (loginLoading.value) {
    console.log('⏭️ Login request in progress, skip repeated clicks')
    return
  }

  // Check if you agree to the agreement
  if (!agreedToTerms.value) {
    ElMessage.warning('Please read and agree to the User Agreement and Privacy Policy first')
    return
  }

  try {
    await loginFormRef.value.validate()

    loginLoading.value = true
    console.log('🔐 Start the login process...')

    // Call real login API
    const success = await authStore.login({
      username: loginForm.username,
      password: loginForm.password
    })

    if (success) {
      console.log('✅ Login successful')
      // Remember the user has agreed to the agreement
      localStorage.setItem('terms-accepted', 'true')
      ElMessage.success('Login successful')

      // Jump to redirect path or dashboard
      const redirectPath = authStore.getAndClearRedirectPath()
      console.log('🔄 redirect to:', redirectPath)
      router.push(redirectPath)
    } else {
      ElMessage.error('Wrong username or password')
    }

  } catch (error) {
    console.error('Login failed:', error)
    // Show error message only if it s not a form validation error
    const errorMessage = error instanceof Error ? error.message : String(error)
    if (errorMessage && !errorMessage.includes('validate')) {
      ElMessage.error('Login failed, please try again')
    }
  } finally {
    loginLoading.value = false
  }
}


</script>

