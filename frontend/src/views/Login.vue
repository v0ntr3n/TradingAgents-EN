          TradingAgents-CN It is an AI multi-Agents investment research and learning platform. The research conclusions, opinions and research summaries in the platform are automatically generated by AI and are only used for learning, research and communication and do not constitute any form of investment advice or commitment. Any investment behavior carried out by the user and the risks and consequences thereof shall be borne by the user himself. The market is risky and decisions need to be made with caution.
        </p>
      </div>
