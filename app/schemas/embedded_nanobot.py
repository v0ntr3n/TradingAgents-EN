from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field, field_validator


class EmbeddedNanobotThreadContext(BaseModel):
    spec_id: str | None = None
    spec_name: str | None = None
    workshop_session_id: str | None = None
    version_id: str | None = None
    version_status: str | None = None
    workflow_id: str | None = None
    node_id: str | None = None
    preference_id: str | None = None
    debug_template_id: str | None = None
    has_blocking_gaps: bool | None = None
    evaluation_status: str | None = None
    intent: dict[str, Any] | None = None
    symbol: str | None = None
    stock_symbol: str | None = None
    object_type: str | None = None
    object_key: str | None = None


class EmbeddedNanobotChatRequest(BaseModel):
    message: str = Field(..., min_length=1, description="User input message")
    display_message: str | None = Field(default=None, description="Raw user input for front-end display")
    session_key: str | None = Field(default=None, description="Session ID. If not passed, it will be generated by default according to the user dimension.")
    model: str | None = Field(default=None, description="Preferred model name")
    channel: str = Field(default="api", description="Source channel")
    chat_id: str | None = Field(default=None, description="Chat ID")
    media: list[str] = Field(default_factory=list, description="Incidental media resources")
    skill_names: list[str] = Field(default_factory=list, description="Explicitly enabled skill name")
    thread_context: EmbeddedNanobotThreadContext | None = Field(default=None, description="Current front-end workbench context")


class EmbeddedNanobotChatResponse(BaseModel):
    content: str
    session_key: str
    thread_id: str | None = None
    stop_reason: str | None = None
    tools_used: list[str] = Field(default_factory=list)
    usage: dict[str, int] = Field(default_factory=dict)
    tool_events: list[dict[str, Any]] = Field(default_factory=list)
    thread_context: dict[str, Any] | None = Field(default=None, description="Thread context persisted after this round of dialogue")


class EmbeddedNanobotThreadItem(BaseModel):
    thread_id: str
    title: str
    session_key: str
    channel: str = "embedded"
    archived: bool = False
    message_count: int = 0
    last_user_message: str = ""
    summary: str = ""
    created_at: str | None = None
    updated_at: str | None = None
    thread_context: EmbeddedNanobotThreadContext | None = None

    @field_validator("created_at", "updated_at", mode="before")
    @classmethod
    def _coerce_datetime_fields(cls, value: Any) -> Any:
        if isinstance(value, datetime):
            return value.isoformat()
        return value


class EmbeddedNanobotThreadListResponse(BaseModel):
    items: list[EmbeddedNanobotThreadItem] = Field(default_factory=list)
    total: int = 0


class EmbeddedNanobotMessageItem(BaseModel):
    message_id: str = ""
    role: str
    content: str
    tools_used: list[str] = Field(default_factory=list)
    stop_reason: str | None = None
    usage: dict[str, int] = Field(default_factory=dict)
    tool_events: list[dict[str, Any]] = Field(default_factory=list)
    created_at: str | None = None

    @field_validator("created_at", mode="before")
    @classmethod
    def _coerce_created_at(cls, value: Any) -> Any:
        if isinstance(value, datetime):
            return value.isoformat()
        return value


class EmbeddedNanobotThreadMessagesResponse(BaseModel):
    thread: EmbeddedNanobotThreadItem | None = None
    messages: list[EmbeddedNanobotMessageItem] = Field(default_factory=list)


class EmbeddedNanobotThreadArchiveResponse(BaseModel):
    archived: bool
    thread_id: str
    deleted_messages: int = 0


class EmbeddedNanobotThreadRestoreResponse(BaseModel):
    restored: bool
    thread_id: str
    archived: bool = False


class EmbeddedNanobotThreadContextUpdateRequest(BaseModel):
    session_key: str | None = None
    channel: str = Field(default="embedded")
    thread_context: EmbeddedNanobotThreadContext = Field(default_factory=EmbeddedNanobotThreadContext)
