async def get_current_user(
    request: Request,
    authorization: Optional[str] = Header(default=None)
) -> dict:
    """
    Get current user information (hybrid authentication)

    Three authentication methods are supported (by priority):
    1. Basic Auth (Only JD Cloud mode,JDYUN_MODE=true Effective) - JD Cloud gateway proxy scenario
    2. JWT Token - for API calls
    3. Session Cookie - for web front-end
    """
    from app.core.jdyun import is_jdyun_mode, verify_jdyun_basic_auth

    request_path = request.url.path if hasattr(request, 'url') else 'unknown'
    has_session_cookie = bool(request.session.get("user_id")) if "session" in request.scope else False
    logger.debug(
        "🔐 Certification check starts: path=%s has_authorization=%s has_session_cookie=%s jdyun_mode=%s",
        request_path,
        bool(authorization),
        has_session_cookie,
        is_jdyun_mode(),
    )

    # way 0: JD Cloud Basic Auth authentication (only JDYUN_MODE=true effective)
    # When JD Cloud Platform proxies a request, it will add Authorization: Basic base64(user:token)
    # where token is the access token generated by JD Cloud for the user (not the login password, decoupled from the user password)
    #
    # Hierarchical verification strategy:
    #   - New user (no record in DB): required username + token All match the environment variable whitelist (anti-forgery)
    #   - Old users (already archived in DB): only verify username, token can be changed arbitrarily (security is controlled by JD Cloud Gateway)
    #
    # After the whitelist verification is passed, the username will be automatically created in the users collection (new user) or returned directly (old user).
    # — 30+ The business code will user["id"] Convert MongoDB ObjectId, so the real record of the database must be returned —
    if is_jdyun_mode() and authorization and authorization.lower().startswith("basic "):
        try:
            import base64
            from app.core.jdyun import is_from_jdyun_gateway

            # ===== The second line of defense: JD Cloud gateway IP whitelist =====
            # Old users are exempted from tokens under hierarchical verification, and the IP whitelist ensures that requests come from JD Cloud Gateway
            # Skip when JDYUN_GATEWAY_IPS is not configured (backward compatibility)
            client_ip = request.client.host if request.client else ""
            if not is_from_jdyun_gateway(client_ip):
                logger.warning(f"❌ [JD Cloud Basic Auth] IP Not in the gateway whitelist, rejected: {client_ip}")
                raise HTTPException(
                    status_code=403,
                    detail="The request source IP is not in the JD Cloud gateway whitelist",
                )

            encoded = authorization.split(" ", 1)[1]
            decoded_bytes = base64.b64decode(encoded, validate=True)
            decoded = decoded_bytes.decode("utf-8")
            if ":" in decoded:
                username, token = decoded.split(":", 1)

                # ===== Graded verification: strict for new users, loose for old users =====
                is_existing = user_service.is_existing_jdyun_user(username)
                if is_existing:
                    # Old users: only verify username (token is variable, security is checked by JD Cloud Gateway)
                    auth_passed = True
                    logger.info(f"✅ [JD Cloud Basic Auth] Old users are exempt from token verification: user={username}")
                else:
                    # First-time authentication for new users: required username + token All match the whitelist
                    auth_passed = verify_jdyun_basic_auth(username, token)
                    if not auth_passed:
                        logger.warning(f"❌ [JD Cloud Basic Auth] New user fails to authenticate for the first time (token mismatch): user={username}")

                if auth_passed:
                    # ===== Certification passed → Automatically create files/reuse real DB records for JD Cloud users =====
                    jdyun_user = await user_service.get_or_create_jdyun_user(
                        jdyun_username=username,
                        is_admin=True,  # The default JD Cloud user is admin (authenticated on the JD Cloud platform side)
                    )
                    if jdyun_user:
                        logger.info(
                            f"✅ [JD Cloud Basic Auth] Authentication successful: user={username} "
                            f"db_id={jdyun_user.id} roles={['admin'] if jdyun_user.is_admin else ['user']} "
                            f"mode={'old user' if is_existing else 'New user profile'}"
                        )
                        return {
                            "id": str(jdyun_user.id),
                            "user_id": str(jdyun_user.id),
                            "username": jdyun_user.username,
                            "email": jdyun_user.email,
                            "name": jdyun_user.username,
                            "is_admin": bool(jdyun_user.is_admin),
                            "roles": ["admin"] if jdyun_user.is_admin else ["user"],
                            "preferences": (
                                jdyun_user.preferences.model_dump()
                                if jdyun_user.preferences
                                else {}
                            ),
                            "auth_method": "basic",
                            "provider": "jdyun",
                        }
                    # Theoretically, it will not reach this point (only if get_or_create_jdyun_user fails), and roll back after logging.
                    logger.error(f"❌ [JD Cloud Basic Auth] User profile failed and virtual user was rolled back: {username}")
            else:
                logger.warning("❌ [JD Cloud Basic Auth] Authorization Format error: Missing number separator")
        except Exception as e:
            logger.warning(f"❌ [JD Cloud Basic Auth] Parsing failed: {e}", exc_info=True)
        # Basic Auth Authentication failed → Continue to follow the original authentication chain (JWT/Session)
        # Note: Basic Auth Is the main path of JD Cloud agent,After failure, even if you use JWT/Session, it will be rejected by the gateway.

    jwt_failed_reason: Optional[str] = None

    # way 1: JWT Token Certification (preferred)
    if authorization and authorization.lower().startswith("bearer "):
        logger.debug("📋 Authentication using JWT Token")

        token = authorization.split(" ", 1)[1]
        logger.debug(
            "🎫 Token information: length=%s fingerprint=%s",
            len(token),
            f"{token[:8]}...{token[-8:]}" if len(token) > 16 else token,
        )

        token_data = AuthService.verify_token(token)
        if not token_data:
            jwt_failed_reason = "token_invalid"
            logger.warning("❌ JWT Authentication failed: token_invalid path=%s", request_path)

        if token_data:
            # Verify session (if session_id is included in token)
            if token_data.session_id:
                session_service = get_session_service()
                session = session_service.verify_session(token_data.session_id, update_activity=True)

                if not session:
                    logger.warning(f"❌ JWT Session Invalid or expired: {token_data.session_id[:16]}...")
                    jwt_failed_reason = "session_expired"
                else:
                    logger.debug(f"✅ JWT Session Verification successful: {token_data.session_id[:16]}...")
            else:
                logger.warning("⚠️ JWT Not carried in session_id: user=%s path=%s", token_data.sub, request_path)

            if jwt_failed_reason is None:
                # Get user information from database
                user = await user_service.get_user_by_username(token_data.sub)
                if user and user.is_active:
                    logger.debug(f"✅ JWT Authentication successful, user: {token_data.sub}")
                    return {
                        "id": str(user.id),
                        "user_id": str(user.id),
                        "username": user.username,
                        "email": user.email,
                        "name": user.username,
                        "is_admin": user.is_admin,
                        "roles": ["admin"] if user.is_admin else ["user"],
                        "preferences": user.preferences.model_dump() if user.preferences else {}
                    }
                jwt_failed_reason = "user_inactive_or_missing"
                logger.warning("❌ JWT Authentication failed: %s user=%s path=%s", jwt_failed_reason, token_data.sub, request_path)
    elif authorization:
        jwt_failed_reason = "authorization_header_not_bearer"
        logger.warning("❌ Authorization Head exists but is not Bearer: path=%s prefix=%s", request_path, authorization[:24])
    else:
        logger.info("ℹ️ The request does not carry the Authorization header: path=%s", request_path)

    if jwt_failed_reason:
        logger.info(f"🔁 JWT Authentication failed({jwt_failed_reason}), try to fallback to Session Cookie: {request_path}")

    # way 2: Session Cookie Authentication (fallback)
    user_id = request.session.get("user_id")
    if user_id:
        logger.debug(f"📋 Using Session Cookie Authentication: user_id={user_id}")

        user = await user_service.get_user_by_id(user_id)
        if user and user.is_active:
            logger.debug(f"✅ Session Authentication successful, user: {user.username}")
            return {
                "id": str(user.id),
                "user_id": str(user.id),
                "username": user.username,
                "email": user.email,
                "name": user.username,
                "is_admin": user.is_admin,
                "roles": ["admin"] if user.is_admin else ["user"],
                "preferences": user.preferences.model_dump() if user.preferences else {}
            }
        else:
            logger.warning(f"❌ Session The user in does not exist or is disabled: {user_id}")
            # clear invalid session
            request.session.clear()
    else:
        logger.info("ℹ️ Session Cookie None user_id: path=%s", request_path)

    # Both ways failed
    logger.warning(
        "❌ Authentication failed: No valid JWT Token or Session Cookie (path: %s, jwt_failed_reason=%s, has_authorization=%s, has_session_cookie=%s)",
        request_path,
        jwt_failed_reason or "none",
        bool(authorization),
        has_session_cookie,
    )
    raise HTTPException(status_code=401, detail="Not logged in or your login has expired")


