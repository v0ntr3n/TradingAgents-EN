@router.put("/me")
async def update_me(
    payload: dict,
    user: dict = Depends(get_current_user)
):
    """Update current user information"""
    try:
        from app.models.user import UserUpdate, UserPreferences

        # Build update data
        update_data = {}

        # Update email
        if "email" in payload:
            update_data["email"] = payload["email"]

        # Update preferences (supports partial updates)
        if "preferences" in payload:
            # Get current preferences
            current_prefs = user.get("preferences", {})

            # Merge new preferences
            merged_prefs = {**current_prefs, **payload["preferences"]}

            # Create UserPreferences object
            update_data["preferences"] = UserPreferences(**merged_prefs)

        # If there is a language setting, update it to the preferences
        if "language" in payload:
            if "preferences" not in update_data:
                # Get current preferences
                current_prefs = user.get("preferences", {})
                update_data["preferences"] = UserPreferences(**current_prefs)
            update_data["preferences"].language = payload["language"]

        # If there is a zone setting, update it in the preferences (if needed)
        # Note: Time zone is usually a system-level setting, not a user-level setting

        # Call service to update user
        user_update = UserUpdate(**update_data)
        updated_user = await user_service.update_user(user["username"], user_update)

        if not updated_user:
            raise HTTPException(status_code=400, detail="Update failed, email may already be in use")

        # Return updated user information
        return {
            "success": True,
            "data": updated_user.model_dump(by_alias=True),
            "message": "User information updated successfully"
        }
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to update user information: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to update user information: {str(e)}")




@router.post("/change-password")
async def change_password(
    payload: ChangePasswordRequest,
    request: Request,
    user: dict = Depends(get_current_user)
):
    """
    Change password (mixed method)

    After changing the password:
    1. Clear Session Cookie (Web Frontend)
    2. Revoke all JWT Sessions (API calls)
    Force user to log in again
    """
    try:
        # Use database service to change password
        success = await user_service.change_password(
            user["username"],
            payload.old_password,
            payload.new_password
        )

        if not success:
            raise HTTPException(status_code=400, detail="Old password is wrong")

        # way 1: Clear Session Cookie
        request.session.clear()
        logger.info(f"✅ Session Cookie cleared: user={user['username']}")

        # way 2: Revoke user's ownership JWT Session
        session_service = get_session_service()
        revoked_count = session_service.revoke_all_user_sessions(user["id"])
        logger.info(f"✅ Password changed successfully and revoked {revoked_count} a JWT Session: user={user['username']}")

        return {
            "success": True,
            "data": {},
            "message": "Password changed successfully, please log in again"
        }
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to change password: {e}")
        raise HTTPException(status_code=500, detail=f"Failed to change password: {str(e)}")

